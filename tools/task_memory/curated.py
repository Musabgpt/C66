"""Hand-written procedures for the apps people here use most (AndroidControl has no Facebook, WhatsApp, Instagram or
Telegram: its demonstrations avoided personal accounts). Each step names the button by every label it has in the
English and the Arabic interface; a step marked optional is skipped when its button is not there (another app version)
and final marks the step that publishes or sends. {1}, {2} are the values the request gives (the post's text, the
contact). The runner tries each label, waits for a slow screen, and stops where the screen differs, so the agent goes
on by hand from there.
"""


def OPEN(name, pkg="", *alt):
    s = {"a": "open_app", "name": name}
    if pkg:
        s["pkg"] = pkg
    if alt:
        s["alt"] = list(alt)
    return s


def TAP(*labels, optional=False, final=False, field=False, hint=""):
    s = {"a": "tap", "t": list(labels)}
    if optional:
        s["optional"] = True
    if final:
        s["final"] = True
    if field:
        s["field"] = True
    if hint:
        s["hint"] = hint
    return s


def TYPE(text, hint=""):
    s = {"a": "type", "text": text}
    if hint:
        s["hint"] = hint
    return s


def KEY(name):
    return {"a": "key", "name": name}


def URL(url, package=""):
    s = {"a": "open_url", "url": url}
    if package:
        s["package"] = package
    return s


def PHONE(action, **args):
    s = {"a": "phone", "action": action}
    s.update(args)
    return s


def SCROLL(direction="down"):
    return {"a": "scroll", "direction": direction}


def WAIT(seconds=1):
    return {"a": "wait", "seconds": seconds}


